// עוזר קטן לבניית תיאור מלא (Portable Text) מתוך טקסט רגיל, כדי שלא לכתוב
// אובייקטי block/span בצורה ידנית וחשופה לשגיאות עבור כל קורס.
function paragraph(text: string, style: "normal" | "em" = "normal"): PortableTextBlock {
  return {
    _type: "block",
    style: "normal",
    children: [{ _type: "span", text, marks: style === "em" ? ["em"] : [] }],
  };
}
function bullet(text: string): PortableTextBlock {
  return {
    _type: "block",
    style: "normal",
    listItem: "bullet",
    level: 1,
    children: [{ _type: "span", text, marks: [] }],
  };
}

